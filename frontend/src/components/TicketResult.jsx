import { useState } from "react";
import { PriorityTag, Tag, cap, secs } from "./ui.jsx";

const SUMMARY_SOURCE = {
  generated: "generated by FLAN-T5 (zero-shot)",
  extractive_fallback: "key sentences from the ticket",
};
const ACTION_SOURCE = {
  rule_based: "rule-based from queue and priority",
  generated: "generated by FLAN-T5 (zero-shot)",
};

/** Customer message → AI draft reply → insights. Used for new analyses and history. */
export default function TicketResult({ ticket }) {
  const [copied, setCopied] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(ticket.generated_response);
      setCopied(true);
      setTimeout(() => setCopied(false), 1600);
    } catch { /* clipboard unavailable */ }
  };
  const t = ticket.timings_ms || {};

  return (
    <div className="thread">
      <div className="message">
        <div className="who">Customer ticket</div>
        {ticket.subject && <div className="subject">{ticket.subject}</div>}
        <div className="text">{ticket.body}</div>
      </div>

      <div className="draft">
        <div className="who">
          <span>Suggested reply, written by <b>{ticket.model_used}</b> (our fine-tuned FLAN-T5)</span>
          {t.response != null && <span className="num">{secs(t.response)}</span>}
        </div>
        <div className="reply">{ticket.generated_response}</div>
        <div className="foot">
          <span className="review-note">Draft for a human agent. Check names, numbers and facts before sending.</span>
          <button className="btn ghost small" onClick={copy}>{copied ? "Copied" : "Copy reply"}</button>
        </div>
      </div>

      <div className="panel">
        <dl className="facts">
          <dt>Summary</dt>
          <dd>{ticket.summary}<span className="source">{SUMMARY_SOURCE[ticket.summary_source] || ticket.summary_source}</span></dd>

          <dt>Recommended action</dt>
          <dd>{ticket.recommended_action}<span className="source">{ACTION_SOURCE[ticket.action_source] || ticket.action_source}</span></dd>

          <dt>Category</dt>
          <dd><Tag value={ticket.category} confidence={ticket.category_confidence} /></dd>

          <dt>Priority</dt>
          <dd><PriorityTag value={ticket.priority} confidence={ticket.priority_confidence} /></dd>

          <dt>Ticket type</dt>
          <dd><Tag value={ticket.ticket_type} confidence={ticket.type_confidence} /></dd>

          <dt>Sentiment</dt>
          <dd><Tag value={ticket.sentiment && cap(ticket.sentiment)} note={ticket.sentiment ? "inferred, not a dataset label" : null} /></dd>
        </dl>
      </div>

      {ticket.warnings?.length > 0 && (
        <div className="alert warn">{ticket.warnings.join(" ")}</div>
      )}
    </div>
  );
}
